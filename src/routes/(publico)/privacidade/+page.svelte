  <span class="selo">RASCUNHO — sujeito a revisão jurídica</span>
  <h1>Política de privacidade</h1>
  <p>Texto-base provisório, elaborado com base na Lei Geral de Proteção de Dados (LGPD, Lei 13.709/2018).</p>
  <h2>1. Papéis no tratamento de dados</h2>
  <p>A oficina é a controladora dos dados dos seus clientes (nomes, contatos, veículos, serviços). A plataforma Mecanica Systems atua como operadora, tratando esses dados conforme as instruções da oficina. Em relação aos dados da conta da própria oficina, a plataforma poderá atuar como controladora.</p>
  <h2>2. Onde os dados ficam</h2>
  <p>Os dados são hospedados no Supabase (região São Paulo) e a aplicação é entregue por meio da Cloudflare.</p>
  <h2>3. Direitos do titular</h2>
  <p>O titular pode solicitar confirmação do tratamento, acesso, correção, anonimização, portabilidade, eliminação, informação sobre compartilhamento e revogação de consentimento. Pedidos relativos a clientes de uma oficina devem ser feitos, em primeiro lugar, à própria oficina.</p>
  <h2>4. Segurança</h2>
  <p>Cada oficina acessa apenas os seus próprios dados, com controle de acesso por usuário e por área.</p>
